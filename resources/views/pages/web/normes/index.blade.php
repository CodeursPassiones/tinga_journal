                                    <h3>Structure de l’article </h3>
                                </div>
                                <div class="sj-description">
                                    <div>
                                        <p>La structure d’un article, doit être conforme aux règles de rédaction
                                            scientifique, selon que l’article est une contribution théorique ou résulte
                                            d’une recherche de terrain.</p>
                                        <p><strong>Pour un article qui est une contribution théorique et fondamentale
                                            </strong>: Titre, Prénom et Nom de l’auteur, Institution d’attache, adresse
                                            électronique, résumé en français, mots clés, Abstract, Key words, Introduction
                                            (justification du sujet, problématique, hypothèses/objectifs scientifiques,
                                            approche), développement articulé, conclusion, bibliographie. </p>
                                        <p><strong>Pour un article qui résulte d’une recherche de terrain
                                            </strong>:titre, prétnom et nom de l’auteur, institution d’attache, adresse
                                            électronique, résumé en français, mots clés, Abstract, Key words, introduction,
                                            méthodologie, résultats et discussion, conclusion, bibliographie. </p>
                                        <p>Les articulations d’un article, à l’exception de l’introduction, de la
                                            conclusion, de la bibliographie, doivent être titrées, et numérotées par des
                                            chiffres (exemples : 1. ; 1.1. ; 1.2 ; 2. ; 2.2. ; 2.2.1 ; 2.2.2. ; 3. ; etc.).
                                            Les passages cités sont présentés en romain et entre guillemets. Lorsque la
                                            phrase citant et la citation dépassent trois lignes, il faut aller à la ligne,
                                            pour présenter la citation (interligne 1) en romain et en retrait, en diminuant
                                            la taille de police d’un point.
                                        </p>
                                        <p><strong>Les références de citation sont intégrées au texte citant, selon les cas,
                                                de la façon suivante
                                            </strong>:Initiale(s) du Prénom ou des Prénoms de l’auteur. Nom de l’Auteur,
                                            année de publication, pages citées) ;
                                            Initiale (s) du Prénom ou des Prénoms de l’auteur. Nom de l’Auteur (année de
                                            publication, pages citées).
                                        </p>
                                        <p style="text-align: center; font-style:italic; font-size: 23px">Exemple</p>
                                        <div>En effet, le but poursuivi par M. Ascher (1998, p. 223), est « d’élargir
                                            l’histoire des mathématiques de telle sorte qu’elle acquière une perspective
                                            multiculturelle et globale (…), d’accroitre le domaine des mathématiques : alors
                                            qu’elle s’est pour l’essentiel occupée du groupe professionnel occidental que
                                            l’on appelle les mathématiciens (…) ».
                                            Pour dire plus amplement ce qu’est cette capacité de la société civile, qui dans
                                            son déploiement effectif, atteste qu’elle peut porter le développement et
                                            l’histoire, S. B. Diagne (1991, p. 2) écrit:
                                            <p style="margin-left: 110px; font-style:italic">Qu’on ne s’y trompe pas : de
                                                toute manière, les
                                                populations ont toujours su
                                                opposer à la philosophie de l’encadrement et à son volontarisme leurs
                                                propres stratégies de contournements. Celles-là, par exemple, sont lisibles
                                                dans le dynamisme, ou à tout le moins, dans la créativité dont sait preuve
                                                ce que l’on désigne sous le nom de secteur informel et à qui il faudra
                                                donner l’appellation positive d’économie populaire.</p>
                                            Le philosophe ivoirien a raison, dans une certaine mesure, de lire, dans ce choc
                                            déstabilisateur, le processus du sous-développement. Ainsi qu’il le dit :
                                            <p style="margin-left: 110px; font-style:italic">le processus du
                                                sous-développement résultant de ce choc est vécu concrètement par les
                                                populations concernées comme une crise globale : crise socio-économique
                                                (exploitation brutale, chômage permanent, exode accéléré et douloureux),
                                                mais aussi crise socio-culturelle et de civilisation traduisant une
                                                impréparation sociohistorique et une inadaptation des cultures et des
                                                comportements humains aux formes de vie imposées par les technologies
                                                étrangères. (S. Diakité, 1985, p. 105).</p>
                                        </div>
                                        <div>
                                            Les sources historiques, les références d’informations orales et les notes
                                            explicatives sont numérotées en série continue et présentées en bas de page.
                                            N.B. : Lorsqu’une citation provient d’une source Internet dont l’auteur est
                                            connu, le principe de présentation des sources dans le texte s’applique, à la
                                            différence qu’il n’y a pas d’indication de page. Lorsqu’il n’y a pas d’auteur,
                                            cette source se place en bas de page.
                                            Les divers éléments d’une référence bibliographique sont présentés comme suit :
                                            NOM et Prénom (s) de l’auteur, Année de publication, Zone titre, Lieu de
                                            publication, Zone Editeur, pages (p.) occupées par l’article dans la revue ou
                                            l’ouvrage collectif. Dans la zone titre, le titre d’un article est présenté en
                                            romain et entre guillemets, celui d’un ouvrage, d’un mémoire ou d’une thèse,
                                            d’un rapport, d’une revue ou d’un journal est présenté en italique. Dans la zone
                                            Editeur, on indique la Maison d’édition (pour un ouvrage), le Nom et le
                                            numéro/volume de la revue (pour un article). Au cas où un ouvrage est une
                                            traduction et/ou une réédition, il faut préciser après le titre le nom du
                                            traducteur et/ou l’édition (ex : 2nde éd.).
                                            Ne sont présentées dans les références bibliographiques que les références des
                                            documents cités. Les références bibliographiques sont présentées par ordre
                                            alphabétique des noms d’auteur.

                                        </div>


